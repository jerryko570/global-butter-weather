'use server'

import { revalidatePath } from 'next/cache'

/**
 * 가게 화면을 다시 굽게 한다. **어드민에서 저장한 뒤에 부른다.**
 *
 * 가게 화면은 60초마다 다시 굽는다(`revalidate = 60`). 매 요청마다 DB 를
 * 때리지 않으려고 그렇게 두었는데, **고친 것이 손님 화면에 뜨기까지 최대
 * 1분이 걸린다.** 2026-09-19에 이나래가 「수정해도 반영이 너무 느리다」고
 * 한 것이 이것이다.
 *
 * 주기를 줄이면 평소 부하가 늘고, 늘리면 더 느려진다. **주기를 건드리는
 * 대신 바뀐 순간에만 깨운다.**
 *
 * `'layout'` 으로 부르는 것은 첫 화면과 상세를 한 번에 잡기 위해서다.
 * 상품 하나만 고쳐도 목록의 이름·가격이 같이 바뀌므로 둘을 나눌 이유가 없다.
 *
 * ⚠️ **이 함수는 권한을 보지 않는다.** 누가 불러도 다시 굽는 것뿐이라
 * 데이터가 새거나 바뀌지 않는다. 다만 자주 부르면 서버가 일한다 — 화면
 * 밖에서 반복해 부를 수 있는 자리가 생기면 그때 제한을 붙인다.
 */
export async function revalidateShop() {
  revalidatePath('/', 'layout')
}
